const RULES_TEMPLATE: &str = r#"<!-- Generated by Project Manager. This block is rewritten automatically; put project-specific rules below the end marker. -->
# Instructions for AI agents

This project is managed with **Project Manager**. Everything an agent needs to
understand the project lives in this `.projectmanager/` folder, as plain Markdown
and JSON. Read and write these files directly; the app does not need to be running.

## Tools (use the first one available)

1. **MCP tools** from the server "project-manager" (`get_project_context`,
   `add_worklog_entry`, `update_state`, `write_doc`, ...): use them; they follow these
   rules for you and add the correct time automatically.
2. **The `pm` command** in a terminal: `pm context` prints a briefing,
   `pm log --author "..." --type feature --title "..." --summary "..."` adds an entry
   with the correct time. Run `pm help` for all options.
3. Otherwise edit the files directly as described below.

## Before you start working

1. Read `STATE.md`: the current state of the project, kept short and up to date.
2. Read the 5 most recent files in `worklog/` (file names sort chronologically).
3. Skim `docs/` for anything relevant to your task (start with `docs/overview.md`).
{READ_SECTIONS}{READ_PROJECT_RULES}
## After every meaningful unit of work (and always before you finish)

### 1. Add a worklog entry

Create a NEW file in `worklog/` named `YYYY-MM-DD_HHMMSS_<author-slug>.md`.
Never edit or delete existing entries: the log is append-only.

**Use the real current time. You have no clock, so never estimate or invent it.**
The MCP tool and `pm log` add it automatically. If you write the file yourself, read
the system clock first and use that value for `date` and for the file name:
`Get-Date -Format "yyyy-MM-ddTHH:mm:sszzz"` (PowerShell) or
`date +%Y-%m-%dT%H:%M:%S%:z` (bash).

Use exactly this format (the date below is only an example):

```markdown
---
date: 2026-11-23T14:30:00+01:00
author: Claude Opus 5.5
type: feature
title: One-line summary of what was done
---

## Summary
What you did and why, in 2-5 sentences.

## Changes
- `path/to/file` - what changed

## Decisions
- The decision and the reason for it, so later agents don't undo it

## Known issues
- Bugs, limitations, things you could not finish

## Next steps
- Concrete suggestions for whoever works next
```

`type` is one of: feature, fix, refactor, docs, research, setup, other.
Write "- none" in a section rather than removing it.

### 2. Update `STATE.md`

If the overall state changed, rewrite `STATE.md` so it stays a current snapshot
(not a history; history belongs in the worklog). Keep it under about 60 lines and
update the "Last updated" line.

### 3. Update or add docs

When you add features, change the architecture, or learn something future agents
need, update `docs/`. One topic per file, lowercase-kebab-case names
(`save-system.md`), with a `# Title` as the first line.
{SECTIONS_STEP}{SECTIONS}
## Rules

- Do not change `project.json` except for `description` or `tags` when asked.
- Never write secrets (API keys, passwords, tokens) into any of these files.
- Write for a reader with zero context: name files, functions and commands explicitly.
"#;

/// The generated rules block (including its start and end markers) for a project
/// with the given extra tabs.
pub fn agents_rules(tabs: &[CustomTab], has_project_rules: bool) -> String {
    let read_sections = if tabs.is_empty() {
        String::new()
    } else {
        "4. Skim the extra sections listed under \"Extra sections\" below.\n".to_string()
    };
    let read_project_rules = if has_project_rules {
        "- Follow the \"Project-specific rules\" at the end of this file; they take priority.\n"
            .to_string()
    } else {
        String::new()
    };
    let (sections_step, sections) = if tabs.is_empty() {
        (String::new(), String::new())
    } else {
        let step = "\n### 4. Keep the extra sections up to date\n\n\
This project has extra sections (tabs in Project Manager), listed below. Whenever your\n\
work affects one of them, update its pages in the same session, following that\n\
section's instructions. This is part of every task, even when nobody asks for it.\n"
            .to_string();
        let mut list = String::from(
            "\n## Extra sections\n\n\
Each section is a folder inside `.projectmanager/` whose Markdown pages are shown as a tab\n\
in Project Manager. Pages: one topic per file, a `# Title` as the first line, and file\n\
names with a two-digit prefix for the reading order (`01-getting-started.md`,\n\
`02-controls.md`). With the MCP tools, use `list_docs`, `read_doc` and `write_doc` with\n\
`section` set to the folder name.\n",
        );
        for t in tabs {
            list.push_str(&format!("\n### {} (folder `{}/`)\n\n", t.title, t.id));
            let instr = t.instructions.trim();
            if instr.is_empty() {
                list.push_str("Keep the pages in this section accurate and up to date.\n");
            } else {
                list.push_str(instr);
                list.push('\n');
            }
        }
        (step, list)
    };
    let body = RULES_TEMPLATE
        .replace("{READ_SECTIONS}", &read_sections)
        .replace("{READ_PROJECT_RULES}", &read_project_rules)
        .replace("{SECTIONS_STEP}", &sections_step)
        .replace("{SECTIONS}", &sections);
    format!("{RULES_START}\n{body}{RULES_END}\n")
}

