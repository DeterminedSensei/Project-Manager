/// The block placed into the project's root AGENTS.md and CLAUDE.md.
pub fn root_pointer(rules_path: &str) -> String {
    format!(
        "{POINTER_START}\n## Project Manager\n\n\
This project's documentation, current state and work log are managed with Project Manager.\n\
**AI agents: read `{rules_path}` before starting and follow its logging rules.**\n\
{POINTER_END}\n"
    )
}

/// The rules file placed into an existing AI folder, e.g. `.claude/project-manager.md`:
/// a short header plus the full content of `.projectmanager/AGENTS.md`.
pub fn ai_folder_rules(agents_md: &str) -> String {
    format!(
        "# Project Manager rules\n\n\
_Generated by Project Manager from `.projectmanager/AGENTS.md`; edit that file instead._\n\n\
The project's current state, documentation and work log are stored in the\n\
`.projectmanager/` folder in the project root. All paths below (`STATE.md`, `AGENTS.md`,\n\
`project.json`, `worklog/`, `docs/` and any extra section folders) are inside `.projectmanager/`.\n\n\
---\n\n{agents_md}"
    )
}

