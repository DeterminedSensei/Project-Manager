/// The first page created with a new tab: (file name, content).
pub fn starter_page(preset: &str, title: &str) -> (String, String) {
    match preset {
        "tutorial" => (
            "01-how-to-play.md".into(),
            "# How to play\n\n_This tutorial has not been written yet. AI agents working on this project \
will write it from the current state of the game and keep it up to date._\n"
                .into(),
        ),
        "design" => (
            "01-vision.md".into(),
            "# Vision\n\n_What the game is, who it is for and what makes it fun. Not written yet._\n".into(),
        ),
        "changelog" => (
            "00-unreleased.md".into(),
            "# Unreleased\n\n- (no player-facing changes recorded yet)\n".into(),
        ),
        _ => (
            "01-overview.md".into(),
            format!("# {}\n\n_Not written yet._\n", title.trim()),
        ),
    }
}

